#!/bin/sh
# Run the ORIGINAL 1993 game in DOSBox-X from a throwaway copy.
#
# The game writes save and state files into its own folder, so we never run it
# from original_bin/. The copy lives in work/dosroot/3K (git-ignored) and is
# created on first run. Delete work/dosroot to reset to a pristine state.
#
# Usage: tools/run-original.sh [--trace] [cycles]
#   --trace  also write a DOSBox-X log to work/logs/trace.log with file I/O
#            (every file the game opens and reads), program launches (exec)
#            and video BIOS calls (int10). The previous log is kept as
#            trace.prev.log. See docs/findings.md for how it is read.
#   cycles   fixed CPU cycles per ms (default 10000, roughly an early-90s
#            486). The game is reported to crash on CPUs that are too fast,
#            so keep this low. Change live with Ctrl+F11 (slower) and
#            Ctrl+F12 (faster) inside DOSBox-X.
set -eu

TRACE=0
CYCLES=10000
for arg in "$@"; do
  case "$arg" in
    --trace) TRACE=1 ;;
    *[!0-9]*|'') echo "Unknown argument: $arg" >&2; exit 2 ;;
    *) CYCLES="$arg" ;;
  esac
done

ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC="$ROOT/original_bin"
DOSROOT="$ROOT/work/dosroot"
PLAY="$DOSROOT/3K"
CONFDIR="$ROOT/work/dosbox"
CONF="$CONFDIR/3k.conf"
LOGDIR="$ROOT/work/logs"
LOG="$LOGDIR/trace.log"

if [ ! -d "$SRC" ]; then
  echo "original_bin/ not found at $SRC" >&2
  exit 1
fi

if [ ! -d "$PLAY" ]; then
  mkdir -p "$PLAY"
  cp -R "$SRC"/. "$PLAY"/
  echo "Created play copy at $PLAY"
fi

mkdir -p "$CONFDIR"

LOGSECTION=""
if [ "$TRACE" -eq 1 ]; then
  mkdir -p "$LOGDIR"
  if [ -f "$LOG" ]; then mv "$LOG" "$LOGDIR/trace.prev.log"; fi
  LOGSECTION="[log]
logfile=$LOG
fileio=true
exec=true
files=true
int10=true
"
fi

cat > "$CONF" <<EOF
# Generated by tools/run-original.sh. Edit the script, not this file.
[sdl]
fullscreen=false

[dosbox]
machine=svga_s3
memsize=16

[cpu]
core=normal
cputype=486
cycles=fixed $CYCLES

$LOGSECTION
[autoexec]
@echo off
mount c "$DOSROOT"
c:
cd \\3k
play
EOF

echo "Starting DOSBox-X (cycles=fixed $CYCLES, trace=$TRACE)"
[ "$TRACE" -eq 1 ] && echo "Log: $LOG"
exec dosbox-x -conf "$CONF"
