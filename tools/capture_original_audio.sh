#!/bin/sh
# Record the audio the ORIGINAL program outputs in DOSBox-X (Sound Blaster + AdLib emulation on),
# unattended: no window (SDL dummy video) and nothing on the speakers (SDL "disk" audio driver
# writes the mixer output to a file in real time: signed 16-bit little-endian, stereo, 48,000 Hz).
#
# Usage: tools/capture_original_audio.sh PROGRAM CYCLES SECONDS OUT.raw [KEYS_AFTER_S:KEY ...]
#   PROGRAM  an executable in the game folder, e.g. mark.exe, or story2x.exe (STORY2.SL copied as
#            .EXE: DOS only starts .EXE/.COM files directly)
#   CYCLES   fixed CPU cycles per ms (run-original.sh uses 10000), or "max"
#   SECONDS  hard time limit: DOSBox-X is killed after this long (SIGALRM), whatever it is doing
# Environment: CAP_OPLEMU=nuked|compat|fast|mame|... picks DOSBox-X's OPL emulation core (default: its own);
# CAP_OPLMODE=opl2 forces the AdLib chip type; CAP_SBTYPE=none turns the Sound Blaster off (AdLib/OPL music only; the programs then
# use their no-sound-card timing); default is DOSBox-X's own default (Sound Blaster on).
# Works in a throwaway copy of the game, work/dosroot_cap/3K (git-ignored; the original_bin files
# are never touched and the game may write its save files there). Delete that folder to reset.
# Read the result with tools/audio_timeline.py.
set -eu
[ $# -ge 4 ] || { sed -n 2,14p "$0"; exit 2; }
PROG=$1; CYCLES=$2; SECS=$3; OUT=$4
case "$SECS" in *[!0-9]*|'') echo "SECONDS must be a number" >&2; exit 2;; esac
ROOT=$(cd "$(dirname "$0")/.." && pwd)
CAP="$ROOT/work/dosroot_cap"
mkdir -p "$CAP" "$ROOT/work/audio_cap"
[ -d "$CAP/3K" ] || cp -R "$ROOT/original_bin" "$CAP/3K"
[ -f "$CAP/3K/STORY2X.EXE" ] || cp "$CAP/3K/STORY2.SL" "$CAP/3K/STORY2X.EXE"
CONF="$ROOT/work/audio_cap/cap.conf"
SBSECTION=""
[ -n "${CAP_SBTYPE:-}" ] && SBSECTION="[sblaster]
sbtype=$CAP_SBTYPE
oplmode=${CAP_OPLMODE:-auto}
oplemu=${CAP_OPLEMU:-default}
"
case "$CYCLES" in max) CY="max";; *[!0-9]*|'') echo "CYCLES must be a number or max" >&2; exit 2;; *) CY="fixed $CYCLES";; esac
cat > "$CONF" <<EOF
# Generated by tools/capture_original_audio.sh
[sdl]
fullscreen=false

[dosbox]
machine=svga_s3
memsize=16

[cpu]
core=normal
cputype=486
cycles=$CY

${SBSECTION}
[autoexec]
@echo off
mount c "$CAP"
c:
cd \\3K
$PROG
EOF
rm -f "$OUT"
SDL_VIDEODRIVER=dummy SDL_AUDIODRIVER=disk SDL_DISKAUDIOFILE="$OUT" \
  perl -e 'alarm shift; exec @ARGV' "$SECS" dosbox-x -conf "$CONF" -nogui > "$OUT.log" 2>&1 || true
ls -l "$OUT"
